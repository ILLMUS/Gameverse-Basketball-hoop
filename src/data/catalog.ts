export function getLevelForXp(xp: number): {
  title: PlayerLevelTitle;
  currentMinXp: number;
  nextMinXp: number | null;
  progressPct: number;
  badgeColor: string;
} {
  let active = LEVEL_THRESHOLDS[0];
  let next: (typeof LEVEL_THRESHOLDS)[number] | null = LEVEL_THRESHOLDS[1];

  for (let i = 0; i < LEVEL_THRESHOLDS.length; i++) {
    if (xp >= LEVEL_THRESHOLDS[i].minXp) {
      active = LEVEL_THRESHOLDS[i];
      next = LEVEL_THRESHOLDS[i + 1] ?? null;
    }
  }

  const progressPct = next
    ? Math.min(100, Math.max(0, ((xp - active.minXp) / (next.minXp - active.minXp)) * 100))
    : 100;

  return {
    title: active.title,
    currentMinXp: active.minXp,
    nextMinXp: next ? next.minXp : null,
    progressPct,
    badgeColor: active.badgeColor,
  };
}

